"""Writes THIRD-PARTY-NOTICES.txt: the license notices of every crate built
into ailimits.exe and ailimits-auth.exe for Windows x64.

Dependency-free (Python 3.8+ and cargo). The crates are those reached from
this package through normal dependencies on x86_64-pc-windows-msvc: no
dev-dependencies, no build-dependencies, and nothing behind a proc-macro
crate (those run at compile time and put none of their own code in the
exes). Each crate's own license and notice files are copied as they ship
with it; a text shared by several crates is written once and named by all.

    python tools/third_party_notices.py          # write the file
    python tools/third_party_notices.py --check  # fail when it is out of date
"""

import hashlib
import json
import os
import re
import subprocess
import sys

TARGET = "x86_64-pc-windows-msvc"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.txt")
FILES = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)", re.I)


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", TARGET],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout
    return json.loads(out)


def shipped(meta):
    """The packages whose code ends up in the exes, the root excluded."""
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]

    def proc_macro(pid):
        return any("proc-macro" in t["kind"] for t in pkgs[pid]["targets"])

    seen, stack = set(), [root]
    while stack:
        pid = stack.pop()
        for dep in nodes[pid]["deps"]:
            normal = any(k["kind"] is None for k in dep["dep_kinds"])
            if not normal or dep["pkg"] in seen or proc_macro(dep["pkg"]):
                continue
            seen.add(dep["pkg"])
            stack.append(dep["pkg"])
    return sorted((pkgs[p] for p in seen), key=lambda p: (p["name"], p["version"]))


def license_texts(pkg):
    """(file name, text) of each license or notice file the crate ships."""
    folder = os.path.dirname(pkg["manifest_path"])
    names = sorted(n for n in os.listdir(folder)
                   if FILES.match(n) and os.path.isfile(os.path.join(folder, n)))
    lf = pkg.get("license_file")
    if lf and os.path.basename(lf) not in names:
        names.append(lf)
    texts = []
    for n in names:
        path = os.path.join(folder, n)
        if os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                texts.append((os.path.basename(n), f.read().replace("\r\n", "\n").strip()))
    return texts


def render(pkgs):
    texts, order, missing = {}, [], []
    lines = [
        "THIRD-PARTY NOTICES",
        "",
        "AI Limits (GPL-3.0-or-later, see LICENSE) is built with the open-source",
        "crates below. Each stays under its own license; its license and notice",
        "files follow, as the crate ships them. Generated by",
        "tools/third_party_notices.py for " + TARGET + "; do not edit by hand.",
        "",
        "=" * 78,
        "CRATES",
        "=" * 78,
        "",
    ]
    for p in pkgs:
        refs = []
        for name, text in license_texts(p):
            key = hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]
            if key not in texts:
                texts[key] = (name, text, [])
                order.append(key)
            texts[key][2].append(f"{p['name']} {p['version']}")
            refs.append(f"[{key}]")
        if not refs:
            missing.append(p["name"])
        src = p.get("repository") or ""
        lines.append(f"{p['name']} {p['version']}  ({p.get('license') or 'see its files'})")
        if src:
            lines.append(f"    {src}")
        lines.append("    texts: " + (" ".join(refs) if refs else
                                        "none shipped with the crate; its license is the SPDX"
                                        " expression above"))
    lines += ["", "=" * 78, "LICENSE AND NOTICE TEXTS", "=" * 78]
    for key in order:
        name, text, users = texts[key]
        lines += ["", "-" * 78, f"[{key}] {name}", "Used by: " + ", ".join(users), "-" * 78, "",
                  text]
    return "\n".join(lines) + "\n", missing


def main():
    body, missing = render(shipped(metadata()))
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read().replace("\r\n", "\n")
        except FileNotFoundError:
            current = ""
        if current != body:
            print("THIRD-PARTY-NOTICES.txt is out of date: "
                  "run python tools/third_party_notices.py", file=sys.stderr)
            return 1
        print("THIRD-PARTY-NOTICES.txt is current")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print(f"wrote {OUT}")
    if missing:
        print("no license file shipped: " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
